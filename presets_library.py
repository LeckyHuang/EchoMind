def get_preset(name: str) -> dict | None:
    """按 slug 查找预设"""
    return next((p for p in PRESET_LIBRARY if p["name"] == name), None)


def get_all_presets() -> list[dict]:
    return PRESET_LIBRARY


def get_preset_prompt(name: str) -> str | None:
    """获取预设的 prompt 文本（已替换 _OUTPUT_RULE 占位符）"""
    preset = get_preset(name)
    if not preset:
        return None
    return preset["prompt"].replace("{_OUTPUT_RULE}", _OUTPUT_RULE.strip())
